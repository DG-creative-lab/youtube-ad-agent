"""Recorded and structured agent run records and their transaction boundaries."""
from dataclasses import dataclass
from typing import ContextManager, Protocol

from .evidence import EvidenceWriter


@dataclass(frozen=True)
class StructuredInferenceRow:
    settings: str
    state: str
    receipt: str | None
    error: str | None


class AgentRunReader(Protocol):
    def scoped_run_row(self, run_id: str, client_id: str, brand_id: str,
                       actor_id: str, campaign_id: str) -> tuple[str, str] | None: ...
    def step_rows(self, run_id: str) -> list[tuple[str, str]]: ...
    def step_count(self, run_id: str) -> int: ...
    def step_exists_row(self, run_id: str, position: int) -> tuple[int] | None: ...
    def structured_source_row(self, run_id: str) -> tuple[str] | None: ...
    def structured_settings_row(self, run_id: str) -> tuple[str] | None: ...
    def structured_start_row(self, run_id: str) -> tuple[str, str] | None: ...
    def structured_inference_row(self, run_id: str) -> StructuredInferenceRow | None: ...


class AgentRunWriter(AgentRunReader, Protocol):
    def create_run(self, run_id: str, client_id: str, brand_id: str, actor_id: str,
                   request: str, status: str, campaign_id: str) -> None: ...
    def create_run_if_id_absent(self, run_id: str, client_id: str, brand_id: str, actor_id: str,
                                request: str, status: str, campaign_id: str) -> None: ...
    def create_run_if_no_conflict(self, run_id: str, client_id: str, brand_id: str, actor_id: str,
                                  request: str, status: str, campaign_id: str) -> None: ...
    def append_step(self, run_id: str, position: int, tool: str, result: str) -> None: ...
    def update_status(self, run_id: str, status: str) -> None: ...
    def add_structured_source(self, run_id: str, source: str, *, ignore_existing: bool = False) -> None: ...
    def add_structured_settings(self, run_id: str, settings: str, *, ignore_existing: bool = False) -> None: ...
    def request_structured_inference(self, run_id: str) -> None: ...
    def fail_structured_inference(self, run_id: str, error: str) -> None: ...
    def receive_structured_inference(self, run_id: str, receipt: str) -> None: ...


class AgentRunWriteUnit(Protocol):
    @property
    def runs(self) -> AgentRunWriter: ...

    @property
    def evidence(self) -> EvidenceWriter: ...

    def commit(self) -> None: ...


class AgentRunStorage(Protocol):
    def read(self) -> ContextManager[AgentRunReader]: ...
    def write(self) -> ContextManager[AgentRunWriteUnit]: ...
