"""Draft state and provenance needed by application validation and revision writes."""
from typing import ContextManager, Protocol


class DraftReader(Protocol):
    def latest_revision_row(self, campaign_id: str) -> tuple[int, str] | None: ...
    def owner_row(self, campaign_id: str) -> tuple[str, str, str, str] | None: ...
    def read_snapshot(self, campaign_id: str, revision: int | None = None) -> str | None: ...
    def live_catalog_entry(self, client_id: str, brand_id: str, campaign_id: str,
                           ref: str) -> tuple[str, str, str, str | None] | None: ...
    def placement_catalog_entry(self, client_id: str, brand_id: str, campaign_id: str,
                                ref: str) -> tuple[str, str, str, str | None] | None: ...


class DraftRepository(DraftReader, Protocol):
    def append_snapshot(self, campaign_id: str, revision: int, snapshot: str) -> None: ...


ApprovalKey = tuple[str, str, str, int, str]
CampaignScope = tuple[str, str, str]
CatalogEntry = tuple[str, str, str, str]
InstructionVersion = tuple[str, str]


class CampaignDraftReader(DraftReader, Protocol):
    """Campaign draft facts on the current unit, including exact approved snapshots."""

    def approval_row(self, key: ApprovalKey) -> tuple[str, str] | None: ...
    def approval_snapshot_row(self, key: ApprovalKey) -> tuple[str, str, str | None] | None: ...
    def approval_history(self, scope: CampaignScope) -> list[tuple[int, str, str, int]]: ...
    def catalog_ref(self, scope: CampaignScope, entry: CatalogEntry) -> str: ...
    def instructions(self, client_id: str, brand_id: str, creative: str, comparison: str) -> list[str]: ...


class CampaignDraftRepository(DraftRepository, CampaignDraftReader, Protocol):
    def append_approval(self, key: ApprovalKey, actor: str, approved_at: str, snapshot: str) -> None: ...
    def register_catalog_entry(self, scope: CampaignScope, ref: str, entry: CatalogEntry) -> None: ...
    def add_instructions(self, client_id: str, brand_id: str, creative: str, comparison: str,
                         versions: list[InstructionVersion]) -> None: ...


class CampaignDraftWriteUnit(Protocol):
    @property
    def drafts(self) -> CampaignDraftRepository: ...

    def commit(self) -> None: ...


class CampaignDraftStorage(Protocol):
    """Writes roll back unless the application explicitly commits the unit."""

    def read(self) -> ContextManager[CampaignDraftReader]: ...
    def write(self) -> ContextManager[CampaignDraftWriteUnit]: ...
