"""Records that share a campaign setup or delivery transaction."""
from typing import ContextManager, Protocol

from campaign_agent.domain.scope import BrandScope
from .drafts import ApprovalKey, CampaignDraftReader

SetupKey = tuple[str, str, str, int, str, str, str]
PublishedLinkRow = tuple[str, str, str, int, float]
CorrectionRow = tuple[str, str, str, str, str, str]


class SetupDeliveryReader(Protocol):
    @property
    def drafts(self) -> CampaignDraftReader: ...

    def setup_snapshot_row(self, key: SetupKey) -> tuple[str] | None: ...
    def publication_rows(self, key: ApprovalKey) -> list[PublishedLinkRow]: ...
    def report_snapshot_row(self, setup_id: str, scenario: str | None) -> tuple[str] | None: ...
    def recommendation_snapshot_row(self, report_id: str) -> tuple[str] | None: ...
    def tagged_activity(self, scope: BrandScope, campaign_id: str, link: dict) -> tuple[int, int]: ...
    def tagged_window(self, scope: BrandScope, campaign_id: str, link: dict,
                      start_ms: int, end_ms: int) -> list[tuple[int, int, int]]: ...
    def correction_row(self, client_id: str, brand_id: str, campaign_id: str, creative_version: str,
                       comparison_version: str, takes_identity: str, comparison_identity: str) -> CorrectionRow | None: ...


class SetupDeliveryWriter(SetupDeliveryReader, Protocol):
    def add_setup(self, key: SetupKey, snapshot: str) -> None: ...
    def update_setup(self, key: SetupKey, snapshot: str) -> None: ...
    def add_report(self, report_id: str, setup_id: str, snapshot: str) -> None: ...
    def add_recommendation(self, recommendation_id: str, report_id: str, snapshot: str) -> None: ...


class SetupDeliveryWriteUnit(SetupDeliveryWriter, Protocol):
    def commit(self) -> None: ...


class SetupDeliveryStorage(Protocol):
    def read(self) -> ContextManager[SetupDeliveryReader]: ...
    def write(self) -> ContextManager[SetupDeliveryWriteUnit]: ...
