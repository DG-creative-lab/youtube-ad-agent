"""Scoped state for comparison visits and published grants."""
from dataclasses import dataclass
from typing import ContextManager, Protocol

from campaign_agent.domain.scope import BrandScope
from .drafts import ApprovalKey, CampaignDraftReader

VisitKey = tuple[str, str, str, str, str]  # visit, client, brand, creative, campaign
ViewerEvent = tuple[str, str, str]  # example, kind, take


@dataclass(frozen=True)
class PublishedGrant:
    client_id: str
    brand_id: str
    campaign_id: str
    revision: int
    fingerprint: str
    creative_ref: str
    snapshot: str


class ViewerReader(Protocol):
    @property
    def drafts(self) -> CampaignDraftReader: ...

    def visit_attribution(self, key: VisitKey) -> tuple[str | None, str | None] | None: ...
    def visit_link_row(self, visit_id: str) -> tuple[str | None] | None: ...
    def event(self, visit_id: str, event_id: str) -> ViewerEvent | None: ...
    def started(self, visit_id: str, example: str, take: str) -> bool: ...
    def finished_takes(self, visit_id: str, example: str) -> list[str]: ...
    def last_choice(self, visit_id: str, example: str) -> str | None: ...
    def completed(self, visit_id: str, example: str) -> bool: ...
    def comparison_counts(self, scope: BrandScope, campaign: str, creative: str, example: str,
                          fingerprint: str) -> tuple[int, int, int, int]: ...
    def verified_setup_link(self, scope: BrandScope, campaign: str, link_id: str) -> dict | None: ...
    def active_grant(self, token: str, now: float) -> PublishedGrant | None: ...
    def active_links(self, key: ApprovalKey, now: float) -> list[tuple[str, str]]: ...


class ViewerWriter(ViewerReader, Protocol):
    def add_visit(self, key: VisitKey, attribution: str | None, link_id: str | None,
                  arrival_ms: int, rehearsal: int | None) -> None: ...
    def clear_attribution(self, visit_id: str) -> None: ...
    def add_arrival(self, visit_id: str, example: str) -> None: ...
    def add_event(self, visit_id: str, event_id: str, event: ViewerEvent) -> None: ...
    def add_completion(self, visit_id: str, example: str, take: str, completed_ms: int) -> None: ...
    def add_publication(self, token: str, grant: PublishedGrant, expires_at: float) -> None: ...


class ViewerWriteUnit(ViewerWriter, Protocol):
    def commit(self) -> None: ...


class ViewerStorage(Protocol):
    def read(self) -> ContextManager[ViewerReader]: ...
    def write(self) -> ContextManager[ViewerWriteUnit]: ...
